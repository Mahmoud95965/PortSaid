export function planRoute(from: string, to: string) {
  if (from === to) return [];
  const q: Array<{ s: string; path: Array<{ l: string; f: string; t: string }>; used: Record<string, boolean> }> = [
    { s: from, path: [], used: {} },
  ];
  const seen: Record<string, boolean> = { [from]: true };

  while (q.length > 0) {
    const cur = q.shift()!;
    for (const line in TRANSPORT_NET) {
      if (cur.used[line] || !TRANSPORT_NET[line].includes(cur.s)) continue;
      for (let i = 0; i < TRANSPORT_NET[line].length; i++) {
        const dest = TRANSPORT_NET[line][i];
        if (dest === cur.s || TRANSPORT_BAN[`${line}|${cur.s}>${dest}`]) continue;
        const np = cur.path.concat([{ l: line, f: cur.s, t: dest }]);
        if (dest === to) return np;
        if (!seen[dest]) {
          seen[dest] = true;
          const u: Record<string, boolean> = { ...cur.used, [line]: true };
          q.push({ s: dest, path: np, used: u });
        }
      }
    }
  }
  return null;
}

